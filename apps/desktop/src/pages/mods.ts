import { open } from "@tauri-apps/plugin-dialog";
import { api, type ModInfo } from "../api";
import { attempt, confirmBox, esc, size, toast } from "../dom";
import { enableReorder } from "../reorder";
import { state, type Page } from "../state";
import { refreshSidebar } from "../shell";
import { openNexus } from "./nexus";

let selected: string | null = null;
let filter = "";

function source(m: ModInfo): string {
  if (m.meta.generated_by) return `Generated by ${m.meta.generated_by}`;
  if (m.meta.nexus) return `Nexus Mods #${m.meta.nexus.mod_id}`;
  return m.meta.source ? m.meta.source.split(/[\\/]/).pop() ?? "" : "—";
}

export async function installMod(): Promise<void> {
  const game = state.game!;
  const picked = await open({ multiple: true, title: "Install mods", filters: [{ name: "Mod archives", extensions: ["zip", "7z", "rar"] }] });
  const files = Array.isArray(picked) ? picked : picked ? [picked] : [];
  for (const f of files) {
    toast(`Installing ${f.split(/[\\/]/).pop()}…`);
    const r = await attempt(() => api.modInstall(game, f));
    if (r) toast(`Installed ${r.name} (${r.files} files)`, "ok");
  }
}

export const modsPage: Page = {
  needsGame: true,
  title: () => "Mods",
  async render(el) {
    const game = state.game!;
    const [mods, conflicts] = await Promise.all([api.mods(game), api.conflicts(game).catch(() => [])]);
    const conflictCount = new Map<string, number>();
    for (const c of conflicts) for (const m of [c.winner, ...c.losers]) conflictCount.set(m, (conflictCount.get(m) ?? 0) + 1);
    if (!mods.some((m) => m.name === selected)) selected = mods[0]?.name ?? null;
    const visible = mods.filter((m) => !filter || m.name.toLowerCase().includes(filter.toLowerCase()));

    el.innerHTML = `
      <div class="split">
        <div class="list">
          <div class="toolbar">
            <input class="input grow" id="mod-filter" placeholder="Filter mods" value="${esc(filter)}" spellcheck="false">
            <button class="btn primary" id="mod-install"><i class="fi">&#xE896;</i>Install mod</button>
          </div>
          <div class="thead mods-grid"><span></span><span>#</span><span></span><span>Name</span><span>Files</span><span>Size</span></div>
          <div class="rows" id="mod-rows">
            ${visible.length ? visible.map((m) => `
              <div class="lrow mods-grid${m.name === selected ? " sel" : ""}" data-name="${esc(m.name)}" draggable="${filter ? "false" : "true"}" data-base="0">
                <span class="grip">&#xE76F;</span>
                <span class="dim">${m.priority}</span>
                <span><div class="toggle${m.enabled ? " on" : ""}" data-toggle></div></span>
                <span class="name">${esc(m.name)}${m.missing ? ' <span class="badge danger">missing</span>' : ""}${conflictCount.has(m.name) ? ` <span class="badge warn" title="files also in other mods">${conflictCount.get(m.name)} conflicts</span>` : ""}${m.meta.generated_by ? ' <span class="badge info">generated</span>' : ""}</span>
                <span class="dim">${m.files}</span>
                <span class="dim">${size(m.bytes)}</span>
              </div>`).join("") : `<div class="empty"><b>No mods yet</b>Install an archive, or download from the Nexus Mods tab.</div>`}
          </div>
        </div>
        <div class="details" id="mod-details"></div>
      </div>`;

    const details = (name: string | null) => {
      const m = mods.find((x) => x.name === name);
      const d = el.querySelector<HTMLElement>("#mod-details")!;
      if (!m) { d.innerHTML = ""; return; }
      const mine = conflicts.filter((c) => c.winner === m.name || c.losers.includes(m.name));
      d.innerHTML = `
        <h2>${esc(m.name)}</h2>
        <div class="dim" style="margin-bottom:16px">${m.meta.version ? `v${esc(m.meta.version)} · ` : ""}priority ${m.priority} (0 wins)</div>
        <div class="card"><div class="kv">
          <span class="k">State</span><span>${m.enabled ? "Enabled" : "Disabled"}</span>
          <span class="k">Files</span><span>${m.files} · ${size(m.bytes)}</span>
          <span class="k">Source</span><span>${esc(source(m))}</span>
          ${m.meta.installed ? `<span class="k">Installed</span><span>${new Date(m.meta.installed * 1000).toLocaleString()}</span>` : ""}
        </div></div>
        ${mine.length ? `<div class="card" style="margin-top:12px"><h3>Conflicts</h3>${mine.slice(0, 12).map((c) => `<div class="mono dim" style="margin-bottom:6px">${esc(c.path)}<br><span class="${c.winner === m.name ? "" : "faint"}">${c.winner === m.name ? "wins over " + esc(c.losers.join(", ")) : "loses to " + esc(c.winner)}</span></div>`).join("")}${mine.length > 12 ? `<div class="faint">…and ${mine.length - 12} more</div>` : ""}</div>` : ""}
        <div class="card" style="margin-top:12px"><h3>Actions</h3><div class="row wrap">
          <button class="btn" data-act="top">Move to top</button>
          ${m.meta.nexus && state.overview?.nexus_domain ? `<button class="btn" data-act="nexus"><i class="fi">&#xE774;</i>Nexus page</button>` : ""}
          <button class="btn danger" data-act="remove">Remove</button>
        </div></div>`;
      d.querySelector("[data-act=top]")?.addEventListener("click", async () => { await attempt(() => api.modMove(game, m.name, 0)); modsPage.render(el); });
      d.querySelector("[data-act=nexus]")?.addEventListener("click", () => {
        openNexus(`https://www.nexusmods.com/${state.overview!.nexus_domain}/mods/${m.meta.nexus!.mod_id}`);
      });
      d.querySelector("[data-act=remove]")?.addEventListener("click", async () => {
        if (await confirmBox("Remove mod", `Delete ${m.name} and its files? This can't be undone.`, "Remove")) {
          await attempt(() => api.modRemove(game, m.name));
          modsPage.render(el);
          refreshSidebar();
        }
      });
    };
    details(selected);

    const rows = el.querySelector<HTMLElement>("#mod-rows")!;
    rows.addEventListener("click", async (e) => {
      const row = (e.target as HTMLElement).closest<HTMLElement>(".lrow");
      if (!row) return;
      const name = row.dataset.name!;
      if ((e.target as HTMLElement).closest("[data-toggle]")) {
        const m = mods.find((x) => x.name === name)!;
        await attempt(() => api.modSetEnabled(game, name, !m.enabled));
        await modsPage.render(el);
        refreshSidebar();
        return;
      }
      selected = name;
      rows.querySelectorAll(".lrow").forEach((r) => r.classList.toggle("sel", r === row));
      details(name);
    });
    enableReorder(rows, async (name, index) => {
      await attempt(() => api.modMove(game, name, index));
      await modsPage.render(el);
      refreshSidebar();
    });
    el.querySelector("#mod-install")!.addEventListener("click", async () => { await installMod(); await modsPage.render(el); refreshSidebar(); });
    const f = el.querySelector<HTMLInputElement>("#mod-filter")!;
    f.addEventListener("input", () => { filter = f.value; Promise.resolve(modsPage.render(el)).then(() => { const n = el.querySelector<HTMLInputElement>("#mod-filter")!; n.focus(); n.setSelectionRange(n.value.length, n.value.length); }); });
  },
};
